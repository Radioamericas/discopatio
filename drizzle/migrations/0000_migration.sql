-- Atomic counters / redeem helpers
create or replace function public.redeem_access_code(_code text) returns boolean
language plpgsql security definer set search_path = public as $$
declare n int; begin
  update public.access_codes set used_at = now() where code = _code and used_at is null;
  get diagnostics n = row_count; return n > 0; end $$;
create or replace function public.redeem_student_access_code(_code text) returns boolean
language plpgsql security definer set search_path = public as $$
declare n int; begin
  update public.student_access_codes set used_at = now() where code = _code and used_at is null;
  get diagnostics n = row_count; return n > 0; end $$;
revoke execute on function public.redeem_access_code(text) from public, anon, authenticated;
revoke execute on function public.redeem_student_access_code(text) from public, anon, authenticated;
grant execute on function public.redeem_access_code(text) to service_role;
grant execute on function public.redeem_student_access_code(text) to service_role;

create or replace function public.analytics_summary()
returns table(day text, page text, event_type text, views bigint, sessions bigint, total_seconds bigint, clicks bigint, country text, device_type text)
language sql security definer set search_path = public as $$
  select day, page, event_type::text,
    sum(case when event_type = 'page_view' then 1 else 0 end),
    sum(case when event_type = 'session_end' then 1 else 0 end),
    sum(duration_seconds), sum(clicks), country, device_type
  from public.analytics_events
  group by day, page, event_type, country, device_type
  order by day desc limit 500 $$;
revoke execute on function public.analytics_summary() from public, anon, authenticated;
grant execute on function public.analytics_summary() to service_role;

-- First signed-up account becomes the owner (replaces Manus owner account).
create or replace function public.handle_first_owner() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.user_roles where role = 'admin') then
    insert into public.user_roles (user_id, role) values (new.id, 'admin');
  end if;
  return new;
end $$;
create trigger on_auth_user_created_owner after insert on auth.users
for each row execute function public.handle_first_owner();