do $$ declare t text; begin
  foreach t in array array['song_requests','request_activity','active_visitors','site_feedback','access_codes','student_access_codes','site_control','analytics_events'] loop
    execute format('grant all on public.%I to service_role', t);
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

